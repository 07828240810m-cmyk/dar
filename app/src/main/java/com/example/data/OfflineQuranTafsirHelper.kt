    fun lookup(surahId: Int, ayahNumber: Int, ayahText: String): AyahTafsirDetail {
        exactTafsir["${surahId}_$ayahNumber"]?.let { return it }
        val surahSummary = surahThemes[surahId]
            ?: "تُبيّن الآية الكريمة من هذه السورة هداية الله تعالى لعباده، وتدعو إلى تدبّر آياته والعمل الصالح."
        val autoWords = extractNotableWords(ayahText)
        return AyahTafsirDetail(
            tafsirMuyassar = "التفسير الميسر (الآية $ayahNumber): $surahSummary",
            wordMeanings = autoWords
        )
    }

    private fun extractNotableWords(ayahText: String): List<Pair<String, String>> {
        val normAyah = OfflineQuranData.stripArabicTashkeel(ayahText)
        return lexicon.entries
            .filter { (k, _) -> normAyah.contains(OfflineQuranData.stripArabicTashkeel(k)) }
            .take(5)
            .map { it.key to it.value }
    }

