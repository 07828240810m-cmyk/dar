    fun transferDailyTotalToMainGradebook(
        ledger: LedgerSubject,
        grade: GradeLevel,
        section: SectionLetter,
        slot: DailyPeriodSlot,
        directSum: Boolean,
        ensureCalcMode: DailyCalcMode? = null,
        ledgerId: String = _activeLedgerId.value
    ): Int {
        val cur = _state.value
        val slotCols = cur.dailyColumns.filter {
            (it.ledgerId == ledgerId || (ledgerId == "general" && it.ledgerId.isBlank())) && it.slot == slot
        }
        if (slotCols.isEmpty()) return 0
        var transferredCount = 0

        commit { st ->
            val updatedStudents = st.students.map { student ->
                if (student.gradeLevel != grade || student.section != section) {
                    student
                } else {
                    val outOf100 = GradeCalculator.computeDailyOutOf100(
                        studentId = student.id,
                        columns = slotCols,
                        dailyScores = st.dailyScores,
                        directSum = directSum
                    )
                    if (outOf100 == null) {
                        student
                    } else {
                        transferredCount++
                        val rounded = GradeCalculator.applyRounding(
                            outOf100,
                            st.gradebookSettings.enableSmartRounding
                        )
                        val g = student.gradesForLedger(ledgerId)
                        val newG = when (slot) {
                            DailyPeriodSlot.T1_M1 -> {
                                val t1AvgDaily = listOfNotNull(rounded, g.term1Month2Daily).average()
                                g.copy(term1Month1Daily = rounded, term1Daily = t1AvgDaily)
                            }
                            DailyPeriodSlot.T1_M2 -> {
                                val t1AvgDaily = listOfNotNull(g.term1Month1Daily, rounded).average()
                                g.copy(term1Month2Daily = rounded, term1Daily = t1AvgDaily)
                            }
                            DailyPeriodSlot.T2_M1 -> {
                                val t2AvgDaily = listOfNotNull(rounded, g.term2Month2Daily).average()
                                g.copy(term2Month1Daily = rounded, term2Daily = t2AvgDaily)
                            }
                            DailyPeriodSlot.T2_M2 -> {
                                val t2AvgDaily = listOfNotNull(g.term2Month1Daily, rounded).average()
                                g.copy(term2Month2Daily = rounded, term2Daily = t2AvgDaily)
                            }
                        }
                        student.withGradesForLedger(ledgerId, newG)
                    }
                }
            }
            val nextSettings = if (ensureCalcMode != null) {
                st.gradebookSettings.copy(dailyCalcMode = ensureCalcMode)
            } else st.gradebookSettings
            st.copy(students = updatedStudents, gradebookSettings = nextSettings)
        }
        if (transferredCount > 0) {
            emitGradeSavedFeedback("✓ تم ترحيل درجات اليومي لـ $transferredCount طالب")
        }
        return transferredCount
    }

