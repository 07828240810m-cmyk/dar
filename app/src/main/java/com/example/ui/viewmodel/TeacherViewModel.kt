    fun batchUpdateStudentGrades(
        columnKey: String,
        scoreByStudentId: Map<String, Double?>,
        ledgerSubject: LedgerSubject = _activeLedger.value,
        ledgerId: String = _activeLedgerId.value
    ) {
        if (scoreByStudentId.isEmpty()) return
        val targetId = if (ledgerId.isNotBlank()) ledgerId else ledgerSubject.id
        commit { st ->
            st.copy(students = st.students.map { student ->
                if (!scoreByStudentId.containsKey(student.id)) student
                else {
                    val value = scoreByStudentId[student.id]
                    val g = student.gradesForLedger(targetId)
                    val newG = when (columnKey) {
                        "t1m1" -> g.copy(term1Month1 = value)
                        "t1m2" -> g.copy(term1Month2 = value)
                        "t1m3" -> g.copy(term1Month3 = value)
                        "t1d" -> g.copy(term1Daily = value)
                        "mid" -> g.copy(midYearTotal = value)
                        "t2m1" -> g.copy(term2Month1 = value)
                        "t2m2" -> g.copy(term2Month2 = value)
                        "t2m3" -> g.copy(term2Month3 = value)
                        "t2d" -> g.copy(term2Daily = value)
                        "final" -> g.copy(finalExam = value)
                        else -> g
                    }
                    student.withGradesForLedger(targetId, newG)
                }
            })
        }
        emitGradeSavedFeedback("✓ تم حفظ الدرجات لـ ${scoreByStudentId.size} طالب")
    }

