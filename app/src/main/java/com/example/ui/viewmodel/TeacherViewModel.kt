    fun updateStudent(updated: Student) {
        val previous = _state.value.students.find { it.id == updated.id }
        val gradesChanged = previous != null && (
            previous.grades != updated.grades ||
                previous.mathGrades != updated.mathGrades ||
                previous.extraGrades != updated.extraGrades
