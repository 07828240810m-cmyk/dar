            if (!f.exists()) return emptyList()
            val arr = JSONArray(f.readText(Charsets.UTF_8))
            (0 until arr.length()).map { i ->
                val obj = arr.getJSONObject(i)
                val ptsArr = obj.getJSONArray("points")
                val pts = (0 until ptsArr.length()).map { pIdx ->
                    val pObj = ptsArr.getJSONObject(pIdx)
                    AnnotationPoint(pObj.getDouble("x").toFloat(), pObj.getDouble("y").toFloat())
                }
                AnnotationStroke(
                    colorArgb = obj.getLong("color"),
                    strokeWidthDp = obj.getDouble("width").toFloat(),
                    isHighlighter = obj.optBoolean("highlighter", false),
                    points = pts
                )
            }
        } catch (_: Exception) {
            emptyList()
        }
    }

