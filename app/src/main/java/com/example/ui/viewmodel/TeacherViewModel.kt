    fun addBatchTimetableCells(
        newCells: List<TimetableCell>,
        workingDays: Set<SchoolDay>,
        updatedDayPeriodTimes: Map<SchoolDay, List<PeriodTime>>? = null
    ) {
        val safeDays = workingDays.ifEmpty { defaultWorkingDays() }
        commit { st ->
            val merged = st.timetable.toMutableList()
            newCells.forEach { nc ->
                merged.removeAll {
                    it.day == nc.day &&
                        it.periodNumber == nc.periodNumber &&
                        it.gradeLevel == nc.gradeLevel &&
                        it.section == nc.section
                }
                merged += nc
            }
            st.copy(
                profile = st.profile.copy(workingDays = safeDays),
                timetable = merged,
                dayPeriodTimes = updatedDayPeriodTimes ?: st.dayPeriodTimes
            )
        }
        _activeDayPeriod.value = LessonAlarmScheduler.currentDayAndPeriod(_state.value.dayPeriodTimes)
        viewModelScope.launch(Dispatchers.IO) { rescheduleAlarms(_state.value) }
    }

    fun moveOrSwapLessonCell(source: TimetableCell, targetPeriod: Int) {
        if (source.periodNumber == targetPeriod) return
        commit { st ->
            val targetCell = st.timetable.find {
                it.day == source.day &&
                    it.periodNumber == targetPeriod &&
                    it.gradeLevel == source.gradeLevel &&
                    it.section == source.section
            }
            val updatedList = st.timetable.map { cell ->
                when {
                    cell == source -> cell.copy(periodNumber = targetPeriod)
                    targetCell != null && cell == targetCell -> cell.copy(periodNumber = source.periodNumber)
                    else -> cell
                }
            }
            st.copy(timetable = updatedList)
        }
        viewModelScope.launch(Dispatchers.IO) { rescheduleAlarms(_state.value) }
    }

    fun swapPeriodsOnDay(day: SchoolDay, periodA: Int, periodB: Int, teacherFilter: String?) {
        if (periodA == periodB) return
        commit { st ->
            val updatedList = st.timetable.map { cell ->
                val matchesFilter = teacherFilter.isNullOrBlank() ||
                    cell.teacherName.contains(teacherFilter, ignoreCase = true)
                if (cell.day == day && matchesFilter) {
                    when (cell.periodNumber) {
                        periodA -> cell.copy(periodNumber = periodB)
                        periodB -> cell.copy(periodNumber = periodA)
                        else -> cell
                    }
                } else cell
            }
            st.copy(timetable = updatedList)
        }
        viewModelScope.launch(Dispatchers.IO) { rescheduleAlarms(_state.value) }
    }

