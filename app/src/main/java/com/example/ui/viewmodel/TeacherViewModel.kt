        commit { st ->
            st.copy(students = st.students.map { if (it.id == updated.id) updated else it })
        }
        if (gradesChanged) {
            emitGradeSavedFeedback("✓ تم حفظ درجات ${updated.fullName} بنجاح")
        }
    }

    fun addStudent(fullName: String, grade: GradeLevel, section: SectionLetter, notes: String = "") {
        if (fullName.isBlank()) return
        commit { st ->
            val existingInSection = st.students.filter { it.gradeLevel == grade && it.section == section }
            val nextOrder = (existingInSection.maxOfOrNull { it.orderNumber } ?: 0) + 1
            val newStudent = Student(
                id = "st_${System.currentTimeMillis()}_${Random().nextInt(999)}",
                orderNumber = nextOrder,
                fullName = fullName.trim(),
                gradeLevel = grade,
                section = section,
                notes = notes.trim()
            )
            st.copy(students = sortSectionAlphabeticallyAndRenumber(st.students + newStudent, grade, section))
        }
    }

    fun addStudentsBatch(
        rawNames: List<String>,
        grade: GradeLevel,
        section: SectionLetter
    ): Int {
        val cleaned = rawNames.map { it.trim() }.filter { it.isNotBlank() }
        if (cleaned.isEmpty()) return 0
        var addedCount = 0
        commit { st ->
            val existingInSection = st.students.filter { it.gradeLevel == grade && it.section == section }
            val existingNames = existingInSection.map { it.fullName.trim() }.toMutableSet()
            var nextOrder = (existingInSection.maxOfOrNull { it.orderNumber } ?: 0) + 1
            val toAdd = mutableListOf<Student>()
            val baseTime = System.currentTimeMillis()
            cleaned.forEachIndexed { idx, name ->
                if (existingNames.add(name)) {
                    toAdd += Student(
                        id = "st_${baseTime}_${idx}_${Random().nextInt(9999)}",
                        orderNumber = nextOrder++,
                        fullName = name,
                        gradeLevel = grade,
                        section = section
                    )
                }
            }
            addedCount = toAdd.size
            st.copy(students = sortSectionAlphabeticallyAndRenumber(st.students + toAdd, grade, section))
        }
        return addedCount
    }

