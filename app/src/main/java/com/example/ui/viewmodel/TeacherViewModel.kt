    fun ensureAutoGeneratedAccountCredentials(): TeacherProfile {
        val current = _state.value.profile
        val needsUser = current.autoGeneratedUsername.isBlank()
        val needsDevice = current.deviceInstallId.isBlank()
        if (!needsUser && !needsDevice && current.accountUsername.isNotBlank()) return current

        val genUser = current.autoGeneratedUsername.ifBlank {
            com.example.utils.BackupCryptoHelper.generateAutoFourLetterUsername()
        }
        val genDevice = current.deviceInstallId.ifBlank {
            java.util.UUID.randomUUID().toString().replace("-", "").take(24)
        }
        val effectiveUsername = current.accountUsername.ifBlank { genUser }
        val updated = current.copy(
            autoGeneratedUsername = genUser,
            accountUsername = effectiveUsername,
            deviceInstallId = genDevice
        )
        commit { st -> st.copy(profile = updated) }
        return updated
    }

