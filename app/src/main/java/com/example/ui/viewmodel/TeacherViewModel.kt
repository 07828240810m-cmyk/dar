    fun applyInternalUpdateRoster(
        revision: Long,
        includeSchoolRoster: Boolean,
        customRosterText: String
    ): com.example.data.RosterMergeResult {
        val current = _state.value
        val incoming = buildList {
            if (includeSchoolRoster) {
                addAll(com.example.data.InternalRosterData.buildBundledSchoolRoster2026())
            }
            if (customRosterText.isNotBlank()) {
                addAll(com.example.data.InternalRosterData.parseRosterText(customRosterText))
            }
        }
        val mergeRes = com.example.data.InternalRosterData.mergeStudentsPreservingExisting(
            existing = current.students,
            incoming = incoming
        )
        commit { st ->
            st.copy(
                students = mergeRes.students,
                profile = st.profile.copy(
                    appliedInternalUpdateRevision = maxOf(st.profile.appliedInternalUpdateRevision, revision)
                )
            )
        }
        return mergeRes
    }

