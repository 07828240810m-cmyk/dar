    fun updateTimetableCell(updated: TimetableCell) {
        commit { st ->
            val exists = st.timetable.any {
                it.day == updated.day &&
                    it.periodNumber == updated.periodNumber &&
                    it.gradeLevel == updated.gradeLevel &&
                    it.section == updated.section
            }
            val newList = if (exists) {
                st.timetable.map {
                    if (it.day == updated.day &&
                        it.periodNumber == updated.periodNumber &&
                        it.gradeLevel == updated.gradeLevel &&
                        it.section == updated.section
                    ) updated else it
                }
            } else {
                st.timetable + updated
            }
            st.copy(timetable = newList)
        }
        viewModelScope.launch(Dispatchers.IO) { rescheduleAlarms(_state.value) }
    }

