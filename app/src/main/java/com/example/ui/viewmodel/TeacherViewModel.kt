    private fun sortSectionAlphabeticallyAndRenumber(
        students: List<Student>,
        grade: GradeLevel,
        section: SectionLetter
    ): List<Student> {
        val collator = Collator.getInstance(Locale("ar")).apply { strength = Collator.PRIMARY }
        val others = students.filterNot { it.gradeLevel == grade && it.section == section }
        val sectionList = students.filter { it.gradeLevel == grade && it.section == section }
            .sortedWith { a, b -> collator.compare(a.fullName.trim(), b.fullName.trim()) }
            .mapIndexed { idx, s -> s.copy(orderNumber = idx + 1) }
        return renumberSections(others + sectionList)
    }

    private fun renumberSections(students: List<Student>): List<Student> {
        val grouped = students.groupBy { it.gradeLevel to it.section }
        val result = mutableListOf<Student>()
        GradeLevel.entries.forEach { g ->
            SectionLetter.entries.forEach { sec ->
                val list = grouped[g to sec].orEmpty().sortedBy { it.orderNumber }
                list.forEachIndexed { idx, s ->
                    result += s.copy(orderNumber = idx + 1)
                }
            }
        }
        return result
    }

