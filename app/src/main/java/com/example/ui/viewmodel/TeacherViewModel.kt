    fun addExamArchiveItem(
        title: String,
        category: ExamArchiveCategory,
        grade: GradeLevel,
        uri: Uri,
        mimeType: String,
        notes: String
    ): Boolean {
        val ext = when {
            mimeType.contains("pdf", true) -> "pdf"
            mimeType.contains("word", true) || mimeType.contains("doc", true) -> "docx"
            else -> "jpg"
        }
        val saved = copyUriToSubdir(uri, "exam_archive", "exam_${System.currentTimeMillis()}_${Random().nextInt(999)}.$ext")
            ?: return false
        commit { st ->
            val item = ExamArchiveItem(
                id = "ex_${System.currentTimeMillis()}_${Random().nextInt(999)}",
                title = title.trim().ifBlank { "${category.titleAr} - ${grade.shortAr}" },
                category = category,
                gradeLevel = grade,
                fileName = saved,
                mimeType = mimeType,
                notes = notes.trim()
            )
            st.copy(examArchive = listOf(item) + st.examArchive)
        }
        return true
    }

